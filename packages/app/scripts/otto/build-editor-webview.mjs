import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const entry = fileURLToPath(
  new URL("../../src/otto/editor/renderer/webview-entry.ts", import.meta.url),
);
const output = fileURLToPath(
  new URL("../../src/otto/editor/renderer/webview-html.ts", import.meta.url),
);
const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  platform: "browser",
  target: ["ios15", "chrome100"],
  tsconfigRaw: {
    compilerOptions: { target: "ES2022", module: "ESNext", useDefineForClassFields: true },
  },
});
const javascript = result.outputFiles[0]?.text;
if (!javascript) throw new Error("The native editor bundle produced no JavaScript.");
const script = javascript.replace(/<\/script/giu, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,viewport-fit=cover"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src data:; connect-src 'none';"><style>html,body,#editor{margin:0;width:100%;height:100%;overflow:hidden}*{box-sizing:border-box}input,button{font:inherit} .cm-editor{height:100%}.cm-tooltip{max-width:95vw}</style></head><body><script>${script}</script></body></html>`;
await writeFile(
  output,
  `// Generated by packages/app/scripts/otto/build-editor-webview.mjs. Do not edit.\nexport const editorWebViewHtml = ${JSON.stringify(html)};\n`,
);
process.stdout.write(`Native editor WebView: ${Buffer.byteLength(html)} bytes\n`);
