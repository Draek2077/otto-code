import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

// Bundles the math webview payload the same way the mermaid, editor and terminal
// payloads are built (build-mermaid-webview-html.mjs is the reference).
//
// Unlike those, this one also inlines a stylesheet and a font set: the payload
// uses KaTeX's HTML output, which is only legible with katex.min.css and the
// KaTeX woff2 faces. They go in as data URIs so the document stays
// self-contained: a webview loaded from an HTML string has no base URL to
// resolve `fonts/...` against, and reaching the network for a font is not
// something a rendered document is allowed to do.
//
// The result is ~10% of the mermaid payload but still large enough that the
// generated module is only ever reached through a dynamic import() in
// math-formula.tsx. See docs/markdown-rendering.md.

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");
const webviewRoot = path.join(appRoot, "src/components/markdown/math-webview");
const entry = path.join(webviewRoot, "math-webview-entry.ts");
const output = path.join(webviewRoot, "math-webview-html.ts");

const katexCssPath = require.resolve("katex/dist/katex.min.css");
const katexFontsDir = path.join(path.dirname(katexCssPath), "fonts");

/**
 * KaTeX's stylesheet with every `url(fonts/…)` replaced by an inline font.
 *
 * Each face is offered as woff2, woff and ttf; only the woff2 is kept, because
 * every engine a react-native-webview runs on has supported woff2 for years and
 * the other two would triple the payload for nothing.
 */
async function inlineKatexFonts(css) {
  const withoutLegacyFormats = css.replace(
    /,url\(fonts\/[\w-]+\.(?:woff|ttf)\)\s*format\("(?:woff|truetype)"\)/g,
    "",
  );

  const names = new Set();
  for (const match of withoutLegacyFormats.matchAll(/url\(fonts\/([\w-]+)\.woff2\)/g)) {
    names.add(match[1]);
  }

  const inlined = new Map();
  await Promise.all(
    [...names].map(async (name) => {
      const bytes = await fs.readFile(path.join(katexFontsDir, `${name}.woff2`));
      inlined.set(name, `data:font/woff2;base64,${bytes.toString("base64")}`);
    }),
  );

  return withoutLegacyFormats.replace(/url\(fonts\/([\w-]+)\.woff2\)/g, (whole, name) => {
    const uri = inlined.get(name);
    if (!uri) throw new Error(`katex.min.css references a missing font: ${name}.woff2`);
    return `url(${uri})`;
  });
}

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    `${basePath}.jsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "otto-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
  },
};

const [result, css] = await Promise.all([
  esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "iife",
    minify: true,
    platform: "browser",
    target: ["ios15", "chrome100"],
    plugins: [aliasPlugin],
    logLevel: "info",
  }),
  fs.readFile(katexCssPath, "utf8").then(inlineKatexFonts),
]);

const js = result.outputFiles[0]?.text;
if (!js) {
  throw new Error("math webview bundle produced no JavaScript");
}

// `</style` and `</script` cannot appear inside their own element, and KaTeX's
// CSS and JS are both third-party text we do not control.
const escapeForElement = (text, tag) => text.replace(new RegExp(`</${tag}`, "gi"), `<\\/${tag}`);

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
    <style>${escapeForElement(css, "style")}</style>
  </head>
  <body>
    <script>${escapeForElement(js, "script")}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/scripts/build-math-webview-html.mjs.
// Do not edit by hand.

export const mathWebViewHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
