import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Bundles the mermaid webview payload the same way the editor and terminal
// payloads are built (build-editor-webview-html.mjs is the reference).
//
// This is the largest of the three by a wide margin — mermaid is ~3.4 MB
// minified — which is why the generated module is only ever reached through a
// dynamic import() in mermaid-diagram.native.tsx. See docs/markdown-rendering.md.

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");
const webviewRoot = path.join(appRoot, "src/components/markdown/mermaid/webview");
const entry = path.join(webviewRoot, "mermaid-webview-entry.ts");
const output = path.join(webviewRoot, "mermaid-webview-html.ts");

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    `${basePath}.jsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "otto-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
  },
};

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  minify: true,
  platform: "browser",
  target: ["ios15", "chrome100"],
  plugins: [aliasPlugin],
  logLevel: "info",
});

const js = result.outputFiles[0]?.text;
if (!js) {
  throw new Error("mermaid webview bundle produced no JavaScript");
}

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
  </head>
  <body>
    <script>${js}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/scripts/build-mermaid-webview-html.mjs.
// Do not edit by hand.

export const mermaidWebViewHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
