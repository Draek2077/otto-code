const { withAndroidManifest } = require("expo/config-plugins");

// Android rotation follows the device's auto-rotate setting.
//
// Expo's top-level `orientation` is shared by both platforms, and its only
// rotation-unlocking value, "default", also enables all four iOS orientations
// (UISupportedInterfaceOrientations). The app stays portrait-locked on iOS on
// purpose, so Android is unlocked here instead by writing
// android:screenOrientation="unspecified" on the main activity - the exact
// value Expo's own `withOrientation` writes for orientation: "default".
// "unspecified" means: follow the device setting. Landscape is then available
// on tablets, while phones stay portrait unless the user enables auto-rotate
// in the system UI (the OS rotation lock is the user's escape hatch).
//
// `android/` is regenerated by `expo prebuild`, so this must live in a config
// plugin rather than a hand edit to AndroidManifest.xml.
function getMainActivity(androidManifest) {
  const mainActivity = androidManifest?.manifest?.application?.[0]?.activity?.filter?.(
    (e) => e.$["android:name"] === ".MainActivity",
  );
  return mainActivity?.[0] ?? null;
}

module.exports = function withAndroidRotation(config) {
  return withAndroidManifest(config, (cfg) => {
    const mainActivity = getMainActivity(cfg.modResults);
    if (!mainActivity) {
      throw new Error(
        "with-android-rotation: AndroidManifest.xml is missing the required .MainActivity element",
      );
    }
    mainActivity.$["android:screenOrientation"] = "unspecified";
    return cfg;
  });
};
